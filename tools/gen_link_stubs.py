import re
import subprocess
import sys

# Symbols no KiCad build defines in one place, hand-mangled.
EXTRA = {
    'FOOTPRINT_WIZARD_MANAGER::ReloadWizards()': ('__ZN24FOOTPRINT_WIZARD_MANAGER13ReloadWizardsEv', 'T'),
    'GENERATOR_TOOL_PNS_PROXY::ClearRouterChanges()': ('__ZN24GENERATOR_TOOL_PNS_PROXY18ClearRouterChangesEv', 'T'),
}

