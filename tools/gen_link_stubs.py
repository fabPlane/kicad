#!/usr/bin/env python3
"""Regenerate host/headless_link_stubs.cpp from a failed headless link.

KICAD_HEADLESS_API drops the GUI half of pcbnew and eeschema, but a number of the sources it
keeps still reference it from branches that only run with an editor frame.  Until every one of
those has a headless guard, the native host links against aborting stubs.

Usage:
    ninja -C build/headless kicad-api-host-native 2>&1 | sed -n '/Undefined symbols/,$p' > undef.txt
    find build/dev -name '*.cpp.o' -print0 | xargs -0 -n40 -P8 nm -gU > devsyms.txt
    tools/gen_link_stubs.py undef.txt devsyms.txt > host/headless_link_stubs.cpp

`devsyms.txt` comes from a normal (option-OFF) build: it is what says whether a missing symbol is
a function (alias it to the abort thunk) or data (emit a zeroed placeholder), and it supplies the
mangled spellings the demangled linker message does not.
"""
